/**
 * ENG-01, D-05, D-07: invariants of the generated trail profiles.
 *
 * data/generated/trail-profiles.ts is written by scripts/terrain/build-trails.mjs
 * from data/terrain/source/trails.json and the committed DEM; `trails:build
 * -- --check` byte-compares it in data:check. These tests pin its shape, the
 * 0..1 normalisation, the DEM endpoint heights, NFC names (ENG-01 encoding
 * edge) and the RSC-only rule: no client module imports it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { trailProfiles } from '@/data/generated/trail-profiles';
import { TrailsFile } from '@/data/schemas/trail';
import { polylineLength } from '@/lib/trail-profile';

const ROOT = process.cwd();
const read = (rel: string) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const moduleText = read('data/generated/trail-profiles.ts');
const trails = TrailsFile.parse(JSON.parse(read('data/terrain/source/trails.json'))).trails;

const HEADER =
  '// AUTO-GENERATED by scripts/terrain/build-trails.mjs from data/terrain/source/trails.json. Do not edit.';

/** True when `v` has at most three decimals. */
const atMost3Decimals = (v: number) => Math.abs(v * 1000 - Math.round(v * 1000)) < 1e-6;

describe('trail-profiles module', () => {
  test('starts with the AUTO-GENERATED header and has no import', () => {
    expect(moduleText.split('\n')[0]).toBe(HEADER);
    expect(moduleText).not.toMatch(/^\s*import\s/m);
  });

  test('lists exactly the box and coin-flip trails', () => {
    expect(trailProfiles.map((t) => t.id)).toEqual(['hoernliweg-27', 'zmutt-2']);
  });

  test('carries the official SAC grade and waymark number of each trail (D-07)', () => {
    const byId = Object.fromEntries(trailProfiles.map((t) => [t.id, t]));
    expect(byId['hoernliweg-27'].sacGrade).toBe('T4');
    expect(byId['hoernliweg-27'].number).toBe(27);
    expect(byId['zmutt-2'].sacGrade).toBe('T1');
    expect(byId['zmutt-2'].number).toBe(2);
  });
});

describe.each(trailProfiles.map((t) => [t.id, t] as const))('profile %s', (id, profile) => {
  const source = trails.find((t) => t.id === id);

  test('has 128 points with x strictly rising from 0 to 1', () => {
    const xs = profile.points.map((p) => p.x);
    expect(xs).toHaveLength(128);
    expect(xs[0]).toBe(0);
    expect(xs[127]).toBe(1);
    for (let i = 1; i < xs.length; i++) expect(xs[i]).toBeGreaterThan(xs[i - 1]);
  });

  test('keeps x and y in [0, 1] at no more than 3 decimals, spanning the full height range', () => {
    for (const { x, y } of profile.points) {
      expect(x).toBeGreaterThanOrEqual(0);
      expect(x).toBeLessThanOrEqual(1);
      expect(y).toBeGreaterThanOrEqual(0);
      expect(y).toBeLessThanOrEqual(1);
      expect(atMost3Decimals(x)).toBe(true);
      expect(atMost3Decimals(y)).toBe(true);
    }
    const ys = profile.points.map((p) => p.y);
    expect(Math.min(...ys)).toBe(0);
    expect(Math.max(...ys)).toBe(1);
  });

  test('has integer DEM start and end heights between 1000 and 4500 m, climbing', () => {
    for (const h of [profile.start.heightM, profile.end.heightM]) {
      expect(Number.isInteger(h)).toBe(true);
      expect(h).toBeGreaterThanOrEqual(1000);
      expect(h).toBeLessThanOrEqual(4500);
    }
    expect(profile.end.heightM).toBeGreaterThan(profile.start.heightM);
  });

  test('lengthM is the rounded length of the committed polyline', () => {
    expect(source).toBeDefined();
    expect(profile.lengthM).toBe(Math.round(polylineLength(source!.polyline)));
  });

  test('every name and place name equals its NFC normalisation (ENG-01 encoding)', () => {
    for (const s of [profile.name, profile.start.name, profile.end.name]) {
      expect(s).toBe(s.normalize('NFC'));
    }
    expect(profile.start.name).toBe(source!.start.name);
    expect(profile.end.name).toBe(source!.end.name);
  });
});

describe('trails.json names (ENG-01 encoding)', () => {
  test('every trail and place name equals its NFC normalisation', () => {
    for (const t of trails) {
      for (const s of [t.name, t.start.name, t.end.name]) expect(s).toBe(s.normalize('NFC'));
    }
  });
});

describe('RSC-only boundary', () => {
  /** Every source file under `dir` (recursive). */
  function sourceFiles(dir: string): string[] {
    const abs = path.join(ROOT, dir);
    if (!fs.existsSync(abs)) return [];
    const out: string[] = [];
    for (const entry of fs.readdirSync(abs, { withFileTypes: true })) {
      const rel = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'node_modules') out.push(...sourceFiles(rel));
      } else if (/\.(ts|tsx|js|jsx|mjs)$/.test(entry.name)) out.push(rel);
    }
    return out;
  }

  /** True when the first statement (after comments) is the client directive. */
  const isClientModule = (text: string) =>
    /^(?:\s|\/\/[^\n]*\n|\/\*[\s\S]*?\*\/)*['"]use client['"]/.test(text);

  test('no client module under app/, components/ or lib/ imports data/generated/trail-profiles', () => {
    const offenders = ['app', 'components', 'lib'].flatMap(sourceFiles).filter((f) => {
      const text = read(f);
      return isClientModule(text) && /data\/generated\/trail-profiles/.test(text);
    });
    expect(offenders).toEqual([]);
  });

  test('the client-directive detector recognises a client module', () => {
    expect(isClientModule("'use client';\nimport x from 'y';")).toBe(true);
    expect(isClientModule('/** doc */\n"use client";')).toBe(true);
    expect(isClientModule("import x from 'y';\n'use client';")).toBe(false);
  });
});

describe('terrain module stays scalar-only', () => {
  test('data/generated/terrain.ts stays under 4096 bytes and holds no path data', () => {
    const terrainText = read('data/generated/terrain.ts');
    expect(Buffer.byteLength(terrainText)).toBeLessThan(4096);
    expect(terrainText).not.toContain('d="');
  });
});
