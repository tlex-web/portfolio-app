/**
 * D-27: contracts of the coin-flip clip pipeline (scripts/media/build-clip.mjs).
 *
 * The clip and its poster are generated on Tim's machine with ffmpeg and
 * committed; CI only runs `clip:derive -- --check`, which needs neither ffmpeg nor
 * the original. These tests pin the sidecar schema and the budget constants, the
 * shape of the generated module, and the --check behaviour, which runs in a child
 * process against the repo and against throwaway roots (`--root`). ffmpeg never
 * runs here: with no clips, neither mode calls it.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { mediaManifest } from '@/data/generated/media-manifest';
import {
  ClipsSidecar,
  MediaManifest,
  MAX_CLIP_BYTES,
  MAX_CLIP_SECONDS,
  MIN_CLIP_SECONDS,
} from '@/data/schemas/media-manifest';

const ROOT = process.cwd();
const SCRIPT = path.join(ROOT, 'scripts/media/build-clip.mjs');
const MANIFEST_REL = 'data/generated/media-manifest.ts';
const SIDECAR_REL = 'data/media/clips.json';

/** Runs build-clip.mjs with `args`; returns its exit status and combined output. */
function run(args: string[]): { status: number; out: string } {
  try {
    const out = execFileSync(
      process.execPath,
      ['--disable-warning=MODULE_TYPELESS_PACKAGE_JSON', SCRIPT, ...args],
      { cwd: ROOT, encoding: 'utf8', stdio: 'pipe' }
    );
    return { status: 0, out };
  } catch (e) {
    const err = e as { status: number | null; stdout?: string; stderr?: string };
    return { status: err.status ?? -1, out: `${err.stdout ?? ''}${err.stderr ?? ''}` };
  }
}

/** A throwaway root holding the given files (relative path -> text). */
function tempRoot(files: Record<string, string>): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'clip-derive-'));
  for (const [rel, text] of Object.entries(files)) {
    fs.mkdirSync(path.dirname(path.join(dir, rel)), { recursive: true });
    fs.writeFileSync(path.join(dir, rel), text);
  }
  return dir;
}

const roots: string[] = [];
afterAll(() => {
  for (const dir of roots) fs.rmSync(dir, { recursive: true, force: true });
});

const validClip = {
  id: 'coin-flip-toss',
  sourceSha256: 'a'.repeat(64),
  start: 0,
  duration: 8,
  posterAt: 6.5,
  crf: 26,
};

describe('clip sidecar schema and budget (D-27)', () => {
  test('the budget is 1.5 MiB and clips run 4 to 10 seconds (D-27, 4 s minimum since 11-15)', () => {
    expect(MAX_CLIP_BYTES).toBe(1572864);
    expect(MIN_CLIP_SECONDS).toBe(4);
    expect(MAX_CLIP_SECONDS).toBe(10);
  });

  test('accepts an empty sidecar and a valid coin-flip-toss entry', () => {
    expect(ClipsSidecar.safeParse({ clips: [] }).success).toBe(true);
    expect(ClipsSidecar.safeParse({ clips: [validClip] }).success).toBe(true);
    expect(ClipsSidecar.safeParse({ clips: [{ ...validClip, fps: 30 }] }).success).toBe(true);
  });

  test('rejects an unknown key', () => {
    expect(ClipsSidecar.safeParse({ clips: [{ ...validClip, location: 'Zermatt' }] }).success).toBe(false);
  });

  test('accepts 4 and 10 seconds and rejects 3.9 or 10.1 seconds', () => {
    expect(ClipsSidecar.safeParse({ clips: [{ ...validClip, duration: 4, posterAt: 3 }] }).success).toBe(true);
    expect(ClipsSidecar.safeParse({ clips: [{ ...validClip, duration: 10 }] }).success).toBe(true);
    expect(ClipsSidecar.safeParse({ clips: [{ ...validClip, duration: 3.9, posterAt: 3 }] }).success).toBe(false);
    expect(ClipsSidecar.safeParse({ clips: [{ ...validClip, duration: 10.1 }] }).success).toBe(false);
  });

  test('rejects an id other than coin-flip-toss', () => {
    expect(ClipsSidecar.safeParse({ clips: [{ ...validClip, id: 'box-demo' }] }).success).toBe(false);
  });
});

describe('generated media manifest', () => {
  const text = fs.readFileSync(path.join(ROOT, MANIFEST_REL), 'utf8');

  test('starts with the AUTO-GENERATED header, has no import and exports mediaManifest', () => {
    expect(text.split('\n')[0]).toMatch(/^\/\/ AUTO-GENERATED by scripts\/media\/build-clip\.mjs/);
    expect(text).not.toMatch(/^\s*import\s/m);
    expect(text).toMatch(/^export const mediaManifest\b/m);
  });

  test('lists exactly the sidecar clips, each a valid entry within the budget and 4-10 s', () => {
    const sidecar = ClipsSidecar.parse(JSON.parse(fs.readFileSync(path.join(ROOT, SIDECAR_REL), 'utf8')));
    expect(Object.keys(mediaManifest).sort()).toEqual(sidecar.clips.map((c) => c.id).sort());
    expect(MediaManifest.safeParse(mediaManifest).success).toBe(true);
    for (const entry of Object.values(mediaManifest)) {
      expect(entry.bytes).toBeLessThanOrEqual(MAX_CLIP_BYTES);
      expect(entry.durationS).toBeGreaterThanOrEqual(MIN_CLIP_SECONDS);
      expect(entry.durationS).toBeLessThanOrEqual(MAX_CLIP_SECONDS);
      expect(fs.statSync(path.join(ROOT, 'public', entry.src)).size).toBe(entry.bytes);
    }
  });

  test('has the header and interface write mode produces (empty sidecar, throwaway root), byte for byte', () => {
    const dir = tempRoot({ [SIDECAR_REL]: '{ "clips": [] }\n' });
    roots.push(dir);
    const { status, out } = run(['--root', dir]);
    expect(out).toContain('clips: OK');
    expect(status).toBe(0);
    // Only the object literal depends on the clips; the --check tests below prove it against the files.
    const marker = 'MediaClipEntry>> = ';
    const head = (t: string) => t.slice(0, t.indexOf(marker) + marker.length);
    const empty = fs.readFileSync(path.join(dir, MANIFEST_REL), 'utf8');
    expect(empty.endsWith(`${marker}{};\n`)).toBe(true);
    expect(text).toContain(marker);
    expect(head(text)).toBe(head(empty));
  });
});

describe('clip:derive --check', () => {
  test('passes on the repo: the committed clip, poster and manifest match the sidecar', () => {
    const { status, out } = run(['--check']);
    expect(out).toContain('clips: OK');
    expect(status).toBe(0);
  });

  test('fails with a missing line when a sidecar clip has no files', () => {
    const committed = fs.readFileSync(path.join(ROOT, MANIFEST_REL), 'utf8');
    const dir = tempRoot({
      [SIDECAR_REL]: JSON.stringify({ clips: [validClip] }),
      [MANIFEST_REL]: committed,
    });
    roots.push(dir);
    const { status, out } = run(['--check', '--root', dir]);
    expect(out).toMatch(/coin-flip-toss: .*missing/);
    expect(out).toMatch(/clips: \d+ problems/);
    expect(status).toBe(1);
  });

  test('fails when the generated manifest is missing', () => {
    const dir = tempRoot({ [SIDECAR_REL]: '{ "clips": [] }\n' });
    roots.push(dir);
    const { status, out } = run(['--check', '--root', dir]);
    expect(out).toContain(`${MANIFEST_REL} is missing`);
    expect(status).toBe(1);
  });
});
