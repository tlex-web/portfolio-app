/**
 * VERIFY-01: every same-origin asset path the data layer references exists
 * under public/.
 *
 * ROADMAP Phase 12 scope note: the legacy v1 image variants are "deleted only
 * behind an asset-exists Jest test". This is that test. It walks every .ts and
 * .json file under data/ (data/generated/ included, data/__tests__/ skipped),
 * collects each quoted /images/, /terrain/ and /media/ string literal, and
 * checks the file is on disk under public/. Deleting or renaming a referenced
 * asset fails it immediately, whichever generator or hand-written module
 * points at it.
 *
 * Only string literals count. Comments are stripped first (JSDoc and the
 * generated-file headers name script paths such as scripts/media/... and
 * documentation patterns such as `/media/<id>.<hash>.mp4`), and template
 * literals with a `${` placeholder are dynamic, so they are skipped. A literal
 * may contain spaces and parentheses: the v1 file names did.
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DATA = path.join(ROOT, 'data');
const PUBLIC = path.join(ROOT, 'public');
const FAMILIES = ['images', 'terrain', 'media'] as const;

/** A whole quoted literal that starts with one of the asset roots. */
const ASSET_LITERAL = /(["'`])(\/(?:images|terrain|media)\/[^"'`\r\n]+)\1/g;

/** Drop block comments and whole-line `//` comments; string contents survive. */
function stripComments(text: string): string {
  return text.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
}

/** Every asset path literal in `text`, with any query or fragment removed, deduped. */
function findAssetPaths(text: string): string[] {
  const found = new Set<string>();
  for (const m of stripComments(text).matchAll(ASSET_LITERAL)) {
    const literal = m[2];
    if (literal.includes('${')) continue;
    found.add(literal.replace(/[?#].*$/, ''));
  }
  return [...found];
}

/** The subset of `paths` with no file under public/. */
function missingAssets(paths: readonly string[]): string[] {
  return paths.filter((p) => !fs.existsSync(path.join(PUBLIC, p)));
}

/** Every .ts and .json file under data/, recursively, outside __tests__. */
function dataFiles(): string[] {
  return (fs.readdirSync(DATA, { recursive: true }) as string[])
    .filter((f) => /\.(ts|json)$/.test(f))
    .filter((f) => !f.split(/[\\/]/).includes('__tests__'))
    .map((f) => path.join(DATA, f));
}

const referenced = [
  ...new Set(dataFiles().flatMap((f) => findAssetPaths(fs.readFileSync(f, 'utf8')))),
].sort();

describe('asset paths referenced from data/ (VERIFY-01)', () => {
  test('every referenced /images/, /terrain/ and /media/ path exists under public/', () => {
    expect(referenced.length).toBeGreaterThan(0);
    expect(missingAssets(referenced)).toEqual([]);
  });

  test('the walk finds at least one path in each asset family', () => {
    for (const family of FAMILIES) {
      expect(referenced.filter((p) => p.startsWith(`/${family}/`)).length).toBeGreaterThan(0);
    }
  });

  test('the helper reports a made-up path as missing, so the walk cannot pass vacuously', () => {
    const sample = "export const ghost = { src: '/images/does-not-exist.webp' };";
    const paths = findAssetPaths(sample);
    expect(paths).toEqual(['/images/does-not-exist.webp']);
    expect(missingAssets(paths)).toEqual(['/images/does-not-exist.webp']);
  });

  test('the helper strips query and fragment, keeps spaces, and ignores comments and placeholders', () => {
    const sample = [
      '// generated by scripts/media/build-clip.mjs from "/media/in-a-comment.mp4"',
      '/** `/media/<id>.<hash>.mp4` */',
      'const a = "/terrain/contours.abc.svg?v=2#top";',
      "const b = '/images/optimized/A (1) -large.webp';",
      'const c = `/terrain/hillshade-${s}.webp`;',
    ].join('\n');
    expect(findAssetPaths(sample)).toEqual([
      '/terrain/contours.abc.svg',
      '/images/optimized/A (1) -large.webp',
    ]);
  });
});
