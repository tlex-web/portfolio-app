#!/usr/bin/env node

/**
 * Photo derivatives (D-11, D-13, DATA-05, DATA-08): originals -> hashed,
 * rotated, metadata-free derivatives + data/generated/image-manifest.ts
 *
 * Replaces scripts/optimize-images.mjs. That script read full-resolution copies
 * from public/images/optimized/ at build time; those copies are gone (D-11), so
 * derivatives are generated here, on Tim's machine, from the gitignored originals
 * in assets/photos-original/ (D-09) and committed. CI only checks them.
 *
 * Per photo in data/photos/exif-sidecar.json:
 *   - AVIF (quality 50, effort 4) and WebP (quality 82, effort 6) at 640, 1024,
 *     1600 and 2560 px on the long edge (D-13: nothing served above 2560 px);
 *   - one 1200 px JPEG (quality 82, progressive, mozjpeg) for OG images and old
 *     clients.
 * Each is rotated from the EXIF orientation first (`rotate()` with no angle) and
 * encoded with sharp's default output, which keeps no EXIF, XMP, IPTC or ICC.
 * This script must never call a metadata-retaining sharp method (RESEARCH
 * Pitfall 3: they re-leak the GPS block). Dropping the ICC profile is colour-
 * neutral only for sRGB input, so write mode refuses any original whose colour
 * space is not sRGB.
 *
 * File names: public/images/photos/<id>-<long edge>.<first 10 hex of sha256(bytes)>.<ext>.
 * Lossy encoders are not byte-stable across platforms (RESEARCH Pattern 3), so
 * the committed bytes are authoritative and the hash is checked against them.
 *
 * The manifest is a pure function of the derivative files and the sidecar. Write
 * mode builds it from the encoded buffers in memory; --check rebuilds it from the
 * files on disk. Both go through the same assembly (assembleManifest), so they
 * give the same bytes for the same files.
 *
 * Modes:
 *   (default)  needs the originals. Each original's sha256 must equal the
 *              sidecar's (run `npm run photos:exif` first after editing a
 *              photo). In this order (08-REVIEW WR-05):
 *                1. encode every derivative into memory;
 *                2. build the manifest from those buffers and validate it
 *                   (decodable, AVIF and WebP sizes agree, no duplicate name,
 *                   ImageManifest schema);
 *                3. only then write the derivatives and the manifest;
 *                4. delete stale files in public/images/photos/ last.
 *              Any failure in steps 1-2 exits 1 before anything is written or
 *              deleted.
 *   --check    needs no originals (CI). Fails when a manifest file is missing,
 *              its name hash does not match its bytes, its format or size
 *              differs from the manifest, or it carries EXIF/XMP/IPTC/ICC or an
 *              orientation tag; when a file in public/images/photos/ is not in
 *              the manifest; when a legacy path is missing; when a sourceSha256
 *              differs from the sidecar's sha256 (derivatives built from an older
 *              original); or when the manifest text differs from a rebuild from
 *              disk and the sidecar.
 *
 * Usage:
 *   npm run photos:derive               (write; local only)
 *   npm run photos:derive -- --check    (also `npm run data:check`, part of `npm run lint`)
 *
 * Exit code 1 on any failure; prints `photos:derive: OK` otherwise.
 */

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { ExifSidecar } from '../../data/schemas/photo.ts';
import {
  ImageManifest,
  JPEG_LONG_EDGE,
  VARIANT_LONG_EDGES,
} from '../../data/schemas/image-manifest.ts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ORIGINALS_REL = 'assets/photos-original/';
const SIDECAR_REL = 'data/photos/exif-sidecar.json';
const OUT_REL = 'public/images/photos/';
const MANIFEST_REL = 'data/generated/image-manifest.ts';
const ORIGINALS_DIR = path.join(ROOT, ORIGINALS_REL);
const SIDECAR_PATH = path.join(ROOT, SIDECAR_REL);
const OUT_DIR = path.join(ROOT, OUT_REL);
const MANIFEST_PATH = path.join(ROOT, MANIFEST_REL);
const PUBLIC_DIR = path.join(ROOT, 'public');
const URL_PREFIX = '/images/photos/';
const NAME = 'photos:derive';

/** Encoder settings, carried over from optimize-images.mjs. */
const QUALITY = { avif: 50, webp: 82, jpeg: 82 };

/** What sharp reports when it decodes each output format. */
const DECODED = {
  avif: { format: 'heif', compression: 'av1' },
  webp: { format: 'webp' },
  jpg: { format: 'jpeg' },
};

const MANIFEST_HEADER =
  '// AUTO-GENERATED by scripts/photos/build-derivatives.mjs from data/photos/exif-sidecar.json and public/images/photos/. Do not edit.\n' +
  '// Content-hashed derivative URLs (DATA-08, D-13): rotated, metadata-free, at most 2560 px on the long edge.\n';

const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');
const hashedName = (id, edge, ext, bytes) => `${id}-${edge}.${sha256(bytes).slice(0, 10)}.${ext}`;

/** Every output of one photo: [long edge, extension]. */
const OUTPUTS = [
  ...VARIANT_LONG_EDGES.flatMap((edge) => [
    [edge, 'avif'],
    [edge, 'webp'],
  ]),
  [JPEG_LONG_EDGE, 'jpg'],
];

/** The committed sidecar, parsed. Throws with the zod issues when it is invalid. */
function loadSidecar() {
  if (!fs.existsSync(SIDECAR_PATH))
    throw new Error(`${SIDECAR_REL} is missing; run npm run photos:exif`);
  return ExifSidecar.parse(JSON.parse(fs.readFileSync(SIDECAR_PATH, 'utf8')));
}

/** EXIF orientations 5-8 swap width and height. */
function orientedSize(p) {
  return p.orientation !== null && p.orientation >= 5
    ? { width: p.height, height: p.width }
    : { width: p.width, height: p.height };
}

/** The legacy v1 variants of an original, reached through the manifest until Phase 12. */
function legacyOf(p) {
  const base = p.file.replace(/\.jpe?g$/i, '');
  return {
    largeWebp: `/images/optimized/${base}-large.webp`,
    largeJpg: `/images/optimized/${base}-large.jpg`,
    thumbWebp: `/images/optimized/${base}-thumb.webp`,
  };
}

/** Sorted file names in public/images/photos/ (empty when the folder is absent). */
function outFiles() {
  if (!fs.existsSync(OUT_DIR)) return [];
  return fs
    .readdirSync(OUT_DIR, { withFileTypes: true })
    .filter((d) => d.isFile())
    .map((d) => d.name)
    .sort();
}

/**
 * Assemble and validate the manifest. `one(id, edge, ext)` resolves one output to
 * `{ url, width, height }`, or pushes a problem and returns null. Pushes one
 * problem per missing, duplicate or undecodable file and per AVIF/WebP size
 * mismatch; returns { value, text } only when there was none.
 */
async function assembleManifest(sidecar, one, problems) {
  const before = problems.length;
  const manifest = {};

  for (const p of sidecar.photos) {
    const variants = [];
    for (const edge of VARIANT_LONG_EDGES) {
      const avif = await one(p.id, edge, 'avif');
      const webp = await one(p.id, edge, 'webp');
      if (!avif || !webp) continue;
      if (avif.width !== webp.width || avif.height !== webp.height)
        problems.push(
          `${p.id} ${edge}: AVIF ${avif.width} x ${avif.height} and WebP ${webp.width} x ${webp.height} differ`
        );
      variants.push({
        longEdge: edge,
        width: avif.width,
        height: avif.height,
        avif: avif.url,
        webp: webp.url,
      });
    }
    const jpg = await one(p.id, JPEG_LONG_EDGE, 'jpg');
    manifest[p.id] = {
      sourceSha256: p.sha256,
      ...orientedSize(p),
      variants,
      jpeg: jpg && { longEdge: JPEG_LONG_EDGE, width: jpg.width, height: jpg.height, src: jpg.url },
      legacy: legacyOf(p),
    };
  }
  if (problems.length > before) return null;

  const value = ImageManifest.parse(manifest);
  const text =
    MANIFEST_HEADER + `export const imageManifest = ${JSON.stringify(value, null, 2)} as const;\n`;
  return { value, text };
}

/** `{ url, width, height }` of one derivative's bytes, or a problem when sharp cannot decode them. */
async function described(name, bytes, problems) {
  try {
    const md = await sharp(bytes).metadata();
    return { url: URL_PREFIX + name, width: md.width, height: md.height };
  } catch {
    problems.push(`${OUT_REL}${name}: not a decodable image`);
    return null;
  }
}

/** The manifest built from the files in public/images/photos/ (--check). */
function manifestFromDisk(sidecar, problems) {
  const files = outFiles();
  return assembleManifest(
    sidecar,
    async (id, edge, ext) => {
      const re = new RegExp(`^${id}-${edge}\\.[0-9a-f]{10}\\.${ext}$`);
      const hits = files.filter((f) => re.test(f));
      if (hits.length !== 1) {
        problems.push(
          hits.length === 0
            ? `missing ${OUT_REL}${id}-${edge}.<hash>.${ext}`
            : `duplicate ${OUT_REL}${id}-${edge}.*.${ext} (${hits.join(', ')})`
        );
        return null;
      }
      return described(hits[0], fs.readFileSync(path.join(OUT_DIR, hits[0])), problems);
    },
    problems
  );
}

/**
 * The manifest built from the encoded buffers, before anything is written
 * (write mode, WR-05). `encoded` maps `id|edge|ext` to `{ name, bytes }`.
 */
function manifestFromMemory(sidecar, encoded, problems) {
  return assembleManifest(
    sidecar,
    async (id, edge, ext) => {
      const hit = encoded.get(`${id}|${edge}|${ext}`);
      if (!hit) {
        problems.push(`missing encoded ${OUT_REL}${id}-${edge}.<hash>.${ext}`);
        return null;
      }
      return described(hit.name, hit.bytes, problems);
    },
    problems
  );
}

/** Refuse anything but an sRGB original (dropping the ICC profile must stay colour-neutral). */
async function assertSrgb(p, bytes) {
  const md = await sharp(bytes).metadata();
  const iccOk = p.iccDescription === null || p.iccDescription.includes('sRGB');
  if (md.space !== 'srgb' || !iccOk)
    throw new Error(
      `${ORIGINALS_REL}${p.file} is not sRGB (space ${md.space}, ICC "${p.iccDescription}"); ` +
        'convert it to sRGB first, because the derivatives drop the ICC profile'
    );
}

/** Rotate, resize to the long edge (never enlarge) and encode with sharp's default, metadata-free output. */
function encode(bytes, edge, ext) {
  const img = sharp(bytes)
    .rotate()
    .resize({ width: edge, height: edge, fit: 'inside', withoutEnlargement: true });
  if (ext === 'avif') return img.avif({ quality: QUALITY.avif, effort: 4 }).toBuffer();
  if (ext === 'webp') return img.webp({ quality: QUALITY.webp, effort: 6 }).toBuffer();
  return img.jpeg({ quality: QUALITY.jpeg, progressive: true, mozjpeg: true }).toBuffer();
}

async function write() {
  const sidecar = loadSidecar();
  if (!fs.existsSync(ORIGINALS_DIR)) {
    console.log(
      `${NAME}: no originals found in ${ORIGINALS_REL}; derivatives are generated locally (D-11)`
    );
    process.exit(1);
  }

  // 1. Encode everything in memory first, so a failure leaves the committed files untouched.
  const outputs = new Map(); // file name -> bytes
  const encoded = new Map(); // `id|edge|ext` -> { name, bytes }
  const problems = [];
  for (const p of sidecar.photos) {
    const abs = path.join(ORIGINALS_DIR, p.file);
    if (!fs.existsSync(abs)) throw new Error(`original ${ORIGINALS_REL}${p.file} is missing`);
    const bytes = fs.readFileSync(abs);
    if (sha256(bytes) !== p.sha256)
      throw new Error(
        `${ORIGINALS_REL}${p.file} does not match the sidecar sha256; run npm run photos:exif first`
      );
    await assertSrgb(p, bytes);
    for (const [edge, ext] of OUTPUTS) {
      const out = await encode(bytes, edge, ext);
      const name = hashedName(p.id, edge, ext, out);
      const key = `${p.id}|${edge}|${ext}`;
      if (outputs.has(name) || encoded.has(key)) problems.push(`duplicate ${OUT_REL}${name}`);
      outputs.set(name, out);
      encoded.set(key, { name, bytes: out });
    }
    console.log(`${NAME}: encoded ${p.id} (${OUTPUTS.length} files)`);
  }

  // 2. Build and validate the manifest from the buffers; nothing is on disk yet.
  const built = problems.length === 0 ? await manifestFromMemory(sidecar, encoded, problems) : null;
  if (!built) {
    for (const l of problems) console.log(`${NAME}: ${l}`);
    console.log(`${NAME}: ${problems.length} problems; nothing written`);
    process.exit(1);
  }

  // 3. Write the derivatives and the manifest.
  fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const [name, out] of outputs) fs.writeFileSync(path.join(OUT_DIR, name), out);
  fs.mkdirSync(path.dirname(MANIFEST_PATH), { recursive: true });
  fs.writeFileSync(MANIFEST_PATH, built.text, 'utf8');

  // 4. Delete stale derivatives last, once the new set and its manifest are in place.
  for (const f of outFiles()) {
    if (outputs.has(f)) continue;
    fs.unlinkSync(path.join(OUT_DIR, f));
    console.log(`${NAME}: removed stale ${OUT_REL}${f}`);
  }
  console.log(`${NAME}: wrote ${outputs.size} files to ${OUT_REL} and ${MANIFEST_REL}`);
  console.log(`${NAME}: OK`);
}

/** The committed manifest's data, or a problem string. */
function committedManifest(text) {
  const m = /export const imageManifest = ([\s\S]*) as const;\s*$/.exec(text);
  if (!m) return { problem: `${MANIFEST_REL} has no "export const imageManifest = ... as const;"` };
  try {
    return { data: JSON.parse(m[1]) };
  } catch (e) {
    return { problem: `${MANIFEST_REL} does not hold JSON data (${e.message})` };
  }
}

/** Why one manifest file fails the --check rules, or null when it passes. */
async function inspect(url, ext, width, height) {
  const file = url.slice(URL_PREFIX.length);
  const m = /\.([0-9a-f]{10})\.[a-z]+$/.exec(file);
  const p = path.join(OUT_DIR, file);
  if (!fs.existsSync(p)) return 'missing';
  const bytes = fs.readFileSync(p);
  if (!m || sha256(bytes).slice(0, 10) !== m[1])
    return 'sha256 of the bytes does not match the name';
  let md;
  try {
    md = await sharp(bytes).metadata();
  } catch {
    return 'not a decodable image';
  }
  const want = DECODED[ext];
  if (md.format !== want.format || (want.compression && md.compression !== want.compression))
    return `decodes as ${md.format}${md.compression ? `/${md.compression}` : ''}, not ${ext}`;
  if (md.width !== width || md.height !== height)
    return `${md.width} x ${md.height}, the manifest says ${width} x ${height}`;
  const carried = ['exif', 'xmp', 'iptc', 'icc'].filter((k) => md[k]);
  if (md.orientation !== undefined) carried.push('orientation');
  if (carried.length > 0) return `carries ${carried.join(', ')} metadata`;
  return null;
}

async function check() {
  const problems = [];
  const done = () => {
    for (const l of problems) console.log(`${NAME}: ${l}`);
    console.log(problems.length === 0 ? `${NAME}: OK` : `${NAME}: ${problems.length} problems`);
    process.exit(problems.length === 0 ? 0 : 1);
  };

  const sidecar = loadSidecar();
  if (!fs.existsSync(MANIFEST_PATH)) {
    problems.push(`${MANIFEST_REL} is missing; run npm run photos:derive`);
    return done();
  }
  const committedText = fs.readFileSync(MANIFEST_PATH, 'utf8');
  const { data, problem } = committedManifest(committedText);
  if (problem) {
    problems.push(problem);
    return done();
  }
  const parsed = ImageManifest.safeParse(data);
  if (!parsed.success) {
    for (const i of parsed.error.issues)
      problems.push(`schema ${i.path.length ? i.path.join('.') : '(root)'}: ${i.message}`);
    return done();
  }
  const manifest = parsed.data;

  // Ids and source hashes against the sidecar.
  const byId = new Map(sidecar.photos.map((p) => [p.id, p]));
  for (const id of Object.keys(manifest))
    if (!byId.has(id)) problems.push(`${id} is in the manifest but not in ${SIDECAR_REL}`);
  for (const [id, p] of byId) {
    const e = manifest[id];
    if (!e) {
      problems.push(`${id} is in ${SIDECAR_REL} but not in the manifest`);
      continue;
    }
    if (e.sourceSha256 !== p.sha256)
      problems.push(
        `${id}: sourceSha256 differs from the sidecar sha256 (derivatives built from an older original; run npm run photos:derive)`
      );
  }

  // Every manifest file: present, hash = name, format, size, no metadata.
  const referenced = new Set();
  for (const [id, e] of Object.entries(manifest)) {
    const files = [
      ...e.variants.flatMap((v) => [
        [v.avif, 'avif', v.width, v.height],
        [v.webp, 'webp', v.width, v.height],
      ]),
      [e.jpeg.src, 'jpg', e.jpeg.width, e.jpeg.height],
    ];
    for (const [url, ext, w, h] of files) {
      referenced.add(url.slice(URL_PREFIX.length));
      const why = await inspect(url, ext, w, h);
      if (why) problems.push(`${id}: ${OUT_REL}${url.slice(URL_PREFIX.length)} ${why}`);
    }
    for (const url of Object.values(e.legacy))
      if (!fs.existsSync(path.join(PUBLIC_DIR, url)))
        problems.push(`${id}: legacy file public${url} is missing`);
  }

  // Orphans: nothing in public/images/photos/ outside the manifest.
  for (const f of outFiles())
    if (!referenced.has(f)) problems.push(`orphan ${OUT_REL}${f} (not in the manifest)`);

  // The committed text must equal a rebuild from disk and the sidecar.
  if (problems.length === 0) {
    const built = await manifestFromDisk(sidecar, problems);
    if (built && built.text !== committedText)
      problems.push(
        `stale ${MANIFEST_REL} (bytes differ from a rebuild from disk and the sidecar)`
      );
  }
  done();
}

const args = process.argv.slice(2);
const unknown = args.filter((a) => a !== '--check');
if (unknown.length > 0) {
  console.log(`${NAME}: unknown argument(s) ${unknown.join(' ')}; the only flag is --check`);
  process.exit(1);
}

(args.includes('--check') ? check() : write()).catch((e) => {
  if (e && Array.isArray(e.issues)) {
    for (const i of e.issues)
      console.log(`${NAME}: schema ${i.path.length ? i.path.join('.') : '(root)'}: ${i.message}`);
    console.log(`${NAME}: ${e.issues.length} schema violations; nothing written`);
  } else {
    console.log(`${NAME}: ${e && e.message ? e.message : String(e)}`);
  }
  process.exit(1);
});
